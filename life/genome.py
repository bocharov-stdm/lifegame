# genome.py — геном травоядного: какие гены есть и как они называются.
#
# Раньше геном был голым списком, и код обращался к генам по номерам: genom[5],
# `if i == 5 or i == 6`. Теперь у каждого гена есть имя, а подписи для вывода
# лежат здесь же, рядом с определением, а не в отчёте.
#
# Genom — кортеж, поэтому доступ по индексу (v.genom[i]) по-прежнему работает,
# а порядок полей — это порядок столбцов VEGETARIAN_BASE_GENOM в config.py.

from typing import NamedTuple


class Genom(NamedTuple):
    size:            float   # размер: радиус поедания и запас энергии
    speed:           float   # скорость
    vision:          float   # зрение: радиус поиска еды и хищников
    repro_threshold: float   # порог размножения, % от запаса энергии
    repro_share:     float   # доля энергии, которая достаётся потомку, %
    min_y:           float   # верхняя граница слоя обитания, % глубины мира
    max_y:           float   # нижняя граница слоя обитания, % глубины мира


# гены слоя — это проценты, при мутации они не должны выходить за 0‒100
LAYER_GENES = ("min_y", "max_y")

GENE_LABELS = {
    "size":            "размер",
    "speed":           "скорость",
    "vision":          "зрение",
    "repro_threshold": "порог_разм",
    "repro_share":     "доля_потомку",
    "min_y":           "min_y%",
    "max_y":           "max_y%",
}
