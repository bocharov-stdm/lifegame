# config.py — все настройки симуляции в одном месте.
#
# Значения подобраны перебором через headless-прогоны: 5 сидов x 3000 тиков,
# критерии — обе популяции доживают до конца, численность держится в
# играбельном коридоре, геном приходит к оптимуму (а не убегает вверх),
# и есть заметные колебания «хищник — жертва».
#
# Крутить баланс удобно так:
#     python sim_report.py --seeds 1 2 3 --ticks 3000

# ── Окно и мир ───────────────────────────────────────────────────────────────
WIDTH, HEIGHT = 1200, 800

# Мир 6000x4000 подобран под окно: масштаб получается ровно 0.2 по обеим осям,
# то есть картинка не сплющена, а растения видны как 2px, существа как 4px.
# (Прежний мир 60000x12000 давал масштабы 0.02 и 0.067: всё рисовалось одним
# пикселем, а на 720 млн px² хищники почти не встречали добычу и выживали лишь
# потому, что не успевали проголодаться.)
WORLD_WIDTH, WORLD_HEIGHT = 6000, 4000

FPS = 60
TICKS_PER_FRAME = 1          # логических тиков на кадр
DIVIDE_PERIOD   = 30         # раз во сколько тиков существа пробуют делиться

# ── Растения ────────────────────────────────────────────────────────────────
PLANT_RADIUS       = 10
PLANTS_AT_START    = 0
ENERGY_FROM_PLANT  = 50

PLANT_DEPTH_DECAY  = 8.0     # чем больше, тем плотнее еда прижата к поверхности
PLANT_TOP_MARGIN   = 200     # мёртвая зона у самой поверхности

# ожидаемое число новых растений за тик (не вероятность!)
DENSITY_PER_PIXEL  = 1.0417e-7
PLANT_SPAWN_CHANCE = DENSITY_PER_PIXEL * WORLD_WIDTH * WORLD_HEIGHT   # = 2.5

# ── Вегетарианцы ────────────────────────────────────────────────────────────
#              размер  скорость  зрение  порог_разм  доля_потомку  min_y%  max_y%
VEGETARIAN_BASE_GENOM = [40,    10,      400,    70,         30,           5,     100]
VEGETARIANS_AT_START  = 20
VEGETARIAN_SIGMA      = 0.3          # разброс мутаций

VEGETARIAN_ENERGY_PER_SIZE = 2.5     # запас энергии = размер * это
VEGETARIAN_REPRO_RESERVE   = 20      # минимум, что должно остаться у родителя
VEGETARIAN_REPRO_COST      = 10      # фикс-штраф за размножение

# ── Стоимость содержания статов (энергии за тик) ────────────────────────────
# расход = COEF * стат ** POWER, суммарно по трём статам.
#
# ПОКАЗАТЕЛИ ВАЖНЕЕ КОЭФФИЦИЕНТОВ: они решают, есть ли у эволюции компромисс,
# или стат выгодно качать до бесконечности. Выгода от стата растёт так:
#   размер   — радиус поедания равен размеру, значит охват ~ размер²
#   зрение   — радиус поиска еды, значит охват ~ зрение²
#   скорость — примерно линейно
# Цена обязана расти КРУЧЕ выгоды, иначе стат убегает вверх без предела:
# при прежних показателях (1.5 для размера и 1.0 для зрения) размер доходил
# до 450 при базовых 40, а зрение — до 1000 при базовых 400.
SIZE_ENERGY_POWER  = 2.5
SPEED_ENERGY_POWER = 2.0
SIGHT_ENERGY_POWER = 2.0

# Коэффициенты нормированы так, чтобы базовый геном тратил три РАВНЫЕ доли и
# проживал на полном баке ~700 тиков (около 12 секунд) без еды. Одно растение
# даёт 50 энергии — примерно половину бака.
SIZE_ENERGY_COEF  = 4.706e-6         # * размер ** 2.5
SPEED_ENERGY_COEF = 4.762e-4         # * скорость ** 2
SIGHT_ENERGY_COEF = 2.976e-7         # * зрение ** 2

WANDER_RADIUS = 1000                 # радиус случайного блуждания хищника

# ── Хищники ─────────────────────────────────────────────────────────────────
PREDATOR_DIAM        = 40
PREDATOR_BASE_SPEED  = 12
PREDATOR_BASE_VISION = 500.0
PREDATORS_AT_START   = 6

# Запаса хватает примерно на 500 тиков охоты вхолостую (расход ~0.19/тик).
PREDATOR_MAX_ENERGY      = 95
PREDATOR_REPRO_THRESHOLD = 0.85      # доля запаса, с которой хищник готов делиться
PREDATOR_REPRO_COST      = 0.30      # доля запаса, которую он на это тратит
PREDATOR_CHILD_ENERGY    = 0.25      # доля запаса, достающаяся ребёнку
# Размножение хищников намеренно редкое. При частом они выедают добычу под
# ноль и гибнут следом: на шансе 0.5 система разваливалась на 2 сидах из 5.
PREDATOR_DIVIDE_CHANCE   = 0.15
PREDATOR_SIGMA           = 0.30      # разброс мутаций скорости и зрения

# ── Бегство ─────────────────────────────────────────────────────────────────
FLEE_DURATION_SEC = 1
FLEE_TICKS        = int(FLEE_DURATION_SEC * FPS * TICKS_PER_FRAME)
