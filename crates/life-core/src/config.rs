//! Все настройки симуляции в одном месте — перенесены из Python-версии
//! (`python/life/config.py` на теге python-final) вместе с объяснениями, почему значения такие.
//!
//! Значения подобраны перебором через headless-прогоны. Критерии: обе популяции
//! доживают до конца, численность держится в играбельном коридоре, геном
//! приходит к оптимуму (а не убегает вверх), видны колебания «хищник — жертва».
//!
//! Крутить баланс удобно так:
//!     cargo run -p life-report --release -- --seeds 1 2 3 --ticks 3000

// ── Мир ──────────────────────────────────────────────────────────────────────
// Базовый мир 6000x4000 подбирался под окно 1200x800. Прежний мир 60000x12000
// давал на 720 млн px² хищников, которые почти не встречали добычу. Больший мир
// теперь получается масштабом (см. space.rs), при котором плотность всего живого
// остаётся прежней.
pub const WORLD_WIDTH: f64 = 6000.0;
pub const WORLD_HEIGHT: f64 = 4000.0;

/// Раз во сколько тиков существа пробуют делиться.
pub const DIVIDE_PERIOD: u64 = 30;

// ── Растения ────────────────────────────────────────────────────────────────
pub const PLANT_RADIUS: f64 = 10.0;
pub const ENERGY_FROM_PLANT: f64 = 50.0;

// Где растёт еда — профиль по глубине и по ширине (flora.rs), правила мира.
// По умолчанию — как было всегда: экспонента по глубине, равномерно по ширине.

/// Крутизна экспоненты по глубине: чем больше, тем плотнее еда прижата к
/// поверхности. При 8 у дна еды в e^8 ≈ 3000 раз меньше, чем наверху.
pub const PLANT_DEPTH_DECAY: f64 = 8.0;
/// Крутизна экспоненты по ширине, если её выбрать. Мягче, чем по глубине: при 8
/// почти вся еда жалась бы к левому краю, и мир справа пустовал бы.
pub const PLANT_WIDTH_DECAY: f64 = 3.0;
/// Мёртвая зона у самой поверхности, % глубины: при высоте 4000 это 200, как
/// было до профилей. Свойство поверхности, поэтому действует при любом профиле.
pub const PLANT_TOP_MARGIN_PCT: f64 = 5.0;
/// Параметры остальных профилей, пока их не тронули: линейный — у дальнего
/// края 10% еды ближнего; логарифм — изгиб 20 (на середине оси ещё 79% еды, к
/// дальнему краю — обрыв до нуля); волны — 3 богатые полосы с размахом 80%
/// (между полосами еды в 9 раз меньше, чем на пике).
pub const PLANT_LINEAR_END: f64 = 10.0;
pub const PLANT_LOG_BEND: f64 = 20.0;
pub const PLANT_WAVES: f64 = 3.0;
pub const PLANT_WAVE_AMPLITUDE: f64 = 80.0;

/// Ожидаемое число новых растений за тик на пиксель площади (не вероятность!).
pub const DENSITY_PER_PIXEL: f64 = 1.0417e-7;
/// Для базового мира это 2.50008 растения за тик.
pub const PLANT_SPAWN_CHANCE: f64 = DENSITY_PER_PIXEL * WORLD_WIDTH * WORLD_HEIGHT;

/// Потолок растений на базовый мир. Растение исчезает, только когда его съели,
/// и без травоядных их становилось на 2.5 больше каждый тик. В здоровых прогонах
/// пик — 219‒289, потолок с пятикратным запасом на обычную игру не влияет.
/// В большом мире потолок растёт вместе с площадью.
pub const PLANT_MAX: usize = 1500;

// ── Травоядные ──────────────────────────────────────────────────────────────
// Базовый геном травоядного — в таблице генов (`genome/vegetarian.rs`).
pub const VEGETARIANS_AT_START: usize = 20;
/// Разброс мутаций.
pub const VEGETARIAN_SIGMA: f64 = 0.3;

/// Запас энергии = размер * это.
pub const VEGETARIAN_ENERGY_PER_SIZE: f64 = 2.5;
/// Минимум, что должно остаться у родителя после деления.
pub const VEGETARIAN_REPRO_RESERVE: f64 = 20.0;
/// Фиксированный штраф за размножение.
pub const VEGETARIAN_REPRO_COST: f64 = 10.0;

// ── Стоимость содержания статов (энергии за тик) ────────────────────────────
// расход = COEF * стат ** POWER, суммарно по трём статам.
//
// ПОКАЗАТЕЛИ ВАЖНЕЕ КОЭФФИЦИЕНТОВ: они решают, есть ли у эволюции компромисс.
// Выгода от стата растёт так:
//   размер   — радиус поедания равен размеру, значит охват ~ размер²
//   зрение   — радиус поиска еды, значит охват ~ зрение²
//   скорость — примерно линейно
// Цена обязана расти КРУЧЕ выгоды, иначе стат убегает вверх без предела:
// при показателях 1.5 для размера и 1.0 для зрения размер доходил до 450 при
// базовых 40, а зрение — до 1000 при базовых 400.
pub const SIZE_ENERGY_POWER: f64 = 2.5;
pub const SPEED_ENERGY_POWER: f64 = 2.0;
pub const SIGHT_ENERGY_POWER: f64 = 2.0;

// Коэффициенты нормированы так, чтобы базовый геном тратил три РАВНЫЕ доли и
// проживал на полном баке ~700 тиков без еды. Одно растение — полбака.
pub const SIZE_ENERGY_COEF: f64 = 4.706e-6;
pub const SPEED_ENERGY_COEF: f64 = 4.762e-4;
pub const SIGHT_ENERGY_COEF: f64 = 2.976e-7;

/// Двигать крупное тело дороже: цена скорости умножается на (размер / 40) ** это.
/// Базовый геном и хищник (диаметр 40) платят ровно столько же, сколько без
/// множителя. Без него при обилии растений выживали гиганты размером 150‒250.
pub const SPEED_MASS_POWER: f64 = 1.0;

/// Радиус случайного блуждания хищника.
pub const WANDER_RADIUS: f64 = 1000.0;

/// Потолок гена мутагенности (множитель на разброс мутаций и шанс смены
/// стратегии). При 10 сигма травоядных 3.0: геном потомка почти случаен —
/// дальше расти незачем, а без потолка множитель мог бы уйти в бесконечность.
pub const MAX_MUTABILITY: f64 = 10.0;

// ── Поиск соседей ───────────────────────────────────────────────────────────
/// Размер клетки сетки (grid.rs). В Python клетка равнялась самому большому
/// радиусу запроса, и одно дальнозоркое существо раздувало её всем. Здесь
/// клетка фиксирована, а запрос берёт столько клеток, сколько покрывает его
/// собственный радиус. 256 — порядок половины зрения: запрос обычно смотрит
/// 4x4‒5x5 клеток, а пустых клеток немного.
pub const GRID_CELL: f64 = 256.0;

// ── Хищники ─────────────────────────────────────────────────────────────────
pub const PREDATOR_DIAM: f64 = 40.0;
pub const PREDATOR_BASE_SPEED: f64 = 12.0;
pub const PREDATOR_BASE_VISION: f64 = 500.0;
/// Сколько хищников на базовый участок, когда мир начинают с ними
/// (`WorldConfig::with_predators`, `--predators`, галочка игры). По умолчанию
/// мир — травоядные и растения, хищников нет: упор теперь на каннибализм.
pub const PREDATORS_PER_AREA: usize = 6;

/// Запаса хватает примерно на 500 тиков охоты вхолостую (расход ~0.19/тик).
pub const PREDATOR_MAX_ENERGY: f64 = 95.0;
/// Доля запаса, с которой хищник готов делиться.
pub const PREDATOR_REPRO_THRESHOLD: f64 = 0.85;
/// Доля запаса, которую он на это тратит.
pub const PREDATOR_REPRO_COST: f64 = 0.30;
/// Доля запаса, достающаяся ребёнку.
pub const PREDATOR_CHILD_ENERGY: f64 = 0.25;
/// Размножение хищников намеренно редкое. При частом они выедают добычу под
/// ноль и гибнут следом: на шансе 0.5 система разваливалась на 2 сидах из 5.
pub const PREDATOR_DIVIDE_CHANCE: f64 = 0.15;
/// Разброс мутаций скорости и зрения.
pub const PREDATOR_SIGMA: f64 = 0.30;

// Рывок. Травоядные быстро эволюционируют до скорости 25+ и без рывка просто
// уходили от хищника со скоростью 12: хищники вымирали во всех 8 сидах к тику
// 7‒14 тысяч. Вблизи (расстояние между краями тел) хищник бежит быстрее, но
// платит за каждый тик рывка сверх обычного расхода.
pub const PREDATOR_SPRINT_RANGE: f64 = 150.0;
pub const PREDATOR_SPRINT_MULT: f64 = 2.0;
pub const PREDATOR_SPRINT_COST: f64 = 0.1;

/// Сытость. Хищник с запасом выше этой доли не охотится, а бродит. Без неё
/// рывок выедал травоядных под ноль, и следом вымирали сами хищники. Порог
/// пробовали сделать геном без цены — отбор тянул его вверх («обжорство»
/// выгодно каждому), хищники выедали добычу, и вымирало 10 миров из 12.
pub const PREDATOR_HUNGRY: f64 = 0.6;

// Миграция. Хищников мало, и даже при удачном балансе популяция вымирает от
// случайного невезения. Если их осталось меньше MIN, раз в PERIOD тиков с края
// мира приходит новый — но только если есть кого есть (не меньше PREY
// травоядных) и мир начинался с хищниками: «мир без охоты» таким и остаётся.
// В большом мире пороги MIN и PREY растут с площадью.
pub const PREDATOR_MIGRATION_PERIOD: f64 = 500.0;
pub const PREDATOR_MIGRATION_MIN: usize = 3;
pub const PREDATOR_MIGRATION_PREY: usize = 30;

// ── Бегство ─────────────────────────────────────────────────────────────────
/// Сколько тиков травоядное бежит после испуга (секунда при 60 тиках в секунду).
pub const FLEE_TICKS: u32 = 60;

// ── Стратегии ───────────────────────────────────────────────────────────────
/// Шанс, что потомок получит другую стратегию поведения (ген-выбор). Пока у
/// вида один вариант, ген инертен и жребий не тянется (`Mutation::Switch`).
pub const STRATEGY_SWITCH_CHANCE: f64 = 0.02;

/// Медленный ход: стратегия может идти на эту долю своей скорости и платить за
/// скорость по фактическому шагу — по тому же закону `speed ** SPEED_POWER`,
/// что и ген. При квадрате треть скорости стоит девятую часть, и весь расход
/// базового травоядного падает примерно до 70% (у хищника — до 68%): заметная
/// экономия, но ищет такое существо втрое медленнее. Бегство и рывок — всегда
/// на полной скорости.
pub const SLOW_PACE: f64 = 1.0 / 3.0;

// ── Каннибализм ─────────────────────────────────────────────────────────────
/// Правило лаборатории: травоядное съедает сородича, который мельче его в
/// CANNIBAL_RATIO раз по размеру, если тот уже в радиусе поедания. Выключено:
/// базовый мир — мир растительноядных, как в Python-версии, и эталон баланса
/// снят без него. Игра включает его сама (упор — на него, хищники по желанию).
pub const CANNIBALISM: f64 = 0.0;
/// Во сколько раз жертва должна быть мельче. 2.5 — с запасом больше единицы:
/// при отношении около 1 два соседа одного размера ели бы друг друга, и
/// размер решал бы не «кто сильнее», а «кто раньше по номеру».
pub const CANNIBAL_RATIO: f64 = 2.5;
