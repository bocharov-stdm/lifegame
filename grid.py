# grid.py — равномерная сетка для поиска соседей.
#
# ЗАЧЕМ
# Существо интересуется только тем, что попало в радиус его зрения, но перебирало
# ради этого весь мир: стоимость тика росла как «травоядные x растения». Сетка
# режет перебор до соседних клеток.
#
# ГЛАВНЫЙ ТРЮК — КЭШ ОКРЕСТНОСТЕЙ
# Наивная сетка (собирать окрестность на каждый запрос) ускоряет всего в 1.4 раза:
# сам сбор кандидатов съедает то, что выиграно на переборе. Поэтому окрестность 3x3
# считается ОДИН раз на клетку и достаётся всем, кто в этой клетке стоит, — а стоят
# там обычно сразу несколько существ. Запрос превращается в поиск по словарю.
#
# Сетка живёт один тик: существа двигаются, и переносить их между клетками дороже,
# чем построить всё заново.


class Grid:
    """Соседи по клеткам. Строится на тик, спрашивается по координате."""

    __slots__ = ("cell", "cells", "cache")

    def __init__(self, cell, items):
        self.cell = cell
        cells = {}
        for it in items:
            key = (int(it.x // cell), int(it.y // cell))
            bucket = cells.get(key)
            if bucket is None:
                cells[key] = [it]
            else:
                bucket.append(it)
        self.cells = cells
        self.cache = {}

    def near(self, x, y):
        """Все объекты из блока 3x3 вокруг точки.

        Это НАДмножество нужного: расстояние всё равно проверяет вызывающий.
        Гарантия полноты — в размере клетки: блок 3x3 накрывает всё, что ближе
        `cell`, поэтому клетку выбирают не меньше самого большого радиуса запроса
        (этим занимается World, см. world.py).
        """
        cell = self.cell
        key = (int(x // cell), int(y // cell))

        found = self.cache.get(key)
        if found is None:
            get = self.cells.get
            cx, cy = key
            found = []
            for i in (cx - 1, cx, cx + 1):
                for j in (cy - 1, cy, cy + 1):
                    bucket = get((i, j))
                    if bucket:
                        found += bucket
            self.cache[key] = found

        return found
