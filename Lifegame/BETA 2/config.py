# config.py — все параметры симуляции.
#
# Энергетика откалибрована headless-прогонами (tools/calibrate.py) на сидах
# 12345, 777 и 2024 по 20000 тиков: растения ~80, травоядные ~800, хищники ~40,
# без вымираний и без обвала биосферы.

# ── окно и мир ───────────────────────────────────────────────────────────────
WIDTH, HEIGHT = 1200, 600
WORLD_WIDTH, WORLD_HEIGHT = 40000, 20000

FPS = 60
TICKS_PER_FRAME = 1          # логических тиков на кадр (меняется клавишами +/-)
MAX_TICKS_PER_FRAME = 64

RANDOM_SEED = None           # None = случайный сид; число = воспроизводимый прогон

# ── растения ─────────────────────────────────────────────────────────────────
PLANT_RADIUS      = 10
PLANTS_AT_START   = 400
ENERGY_FROM_PLANT = 45

# Ожидаемое число новых растений за тик. Раньше здесь была «вероятность» ≈1.6,
# то есть ровно одно растение за тик детерминированно — теперь это явная
# интенсивность, и дробная часть разыгрывается честно.
PLANT_SPAWN_RATE = 3.0

# Растения гуще у поверхности: плотность ~ exp(-PLANT_DEPTH_DECAY * y / H).
PLANT_DEPTH_DECAY = 7.0

# ── геном ────────────────────────────────────────────────────────────────────
# (имя, базовое значение, тип мутации, нижняя граница, верхняя граница)
#   "mul" — мутация value * (1 + gauss(0, sigma)); годится для величин, у которых
#           осмысленно относительное изменение (размер, скорость, зрение).
#   "add" — мутация value + gauss(0, sigma_pct); обязательна для процентных генов:
#           мультипликативная мутация навсегда запирает значение 0 в нуле.
GENES = [
    ("size",            80.0, "mul", 1.0,  None),
    ("speed",           20.0, "mul", 0.01, None),
    ("vision",        2000.0, "mul", 1.0,  None),
    ("repro_threshold", 50.0, "add", 5.0,  100.0),   # % от max_energy
    ("repro_share",     40.0, "add", 5.0,  90.0),    # % энергии ребёнку
    ("min_y",            5.0, "add", 0.0,  100.0),   # верх слоя обитания, %
    ("max_y",           50.0, "add", 0.0,  100.0),   # низ слоя обитания, %
]
GENE_NAMES = [g[0] for g in GENES]
GENE_INDEX = {name: i for i, name in enumerate(GENE_NAMES)}

MUTATION_SIGMA     = 0.12    # sigma для "mul"-генов (доля значения)
MUTATION_SIGMA_PCT = 3.0     # sigma для "add"-генов (в единицах самого гена)

# ── энергетика ───────────────────────────────────────────────────────────────
# Расход за тик = SIZE*size^1.5 + SPEED*speed^2 + SIGHT*vision + BASAL.
SIZE_ENERGY_COEF  = 0.000008
SPEED_ENERGY_COEF = 0.00010
SIGHT_ENERGY_COEF = 0.00002
BASAL_METABOLISM  = 0.004

MAX_ENERGY_PER_SIZE = 2.5    # max_energy = size * этот коэффициент

# Размножение: доли max_energy, а не абсолютные числа — иначе мелкие и крупные
# особи играют по разным правилам.
REPRO_RESERVE_FRAC = 0.15    # столько должно остаться у родителя
REPRO_COST_FRAC    = 0.05    # штраф за само деление
REPRO_EVERY        = 30      # раз в сколько тиков проверяется размножение

# ── популяции ────────────────────────────────────────────────────────────────
VEGETARIANS_AT_START = 100
VEGETARIAN_BASE_GENOM = [g[1] for g in GENES]

PREDATORS_AT_START = 10
# Хищник крупнее и быстрее жертвы, но видит вдвое ближе неё: жертва замечает
# его первой и успевает убежать. Без этого разрыва в дальности обнаружения
# бегство не срабатывает никогда и хищничество становится детерминированным.
PREDATOR_BASE_GENOM = [120.0, 32.0, 1200.0, 70.0, 35.0, 5.0, 60.0]
# Добыча даёт энергию жертвы плюс её биомассу: иначе хищник, съевший
# истощённое травоядное, не окупает даже собственное переваривание, и хищники
# гарантированно вымирают при любой плотности жертв.
PREDATION_EFFICIENCY = 0.6   # доля добытого, достающаяся хищнику
PREY_BIOMASS_COEF = 0.5      # энергия за единицу размера жертвы
PREDATOR_DIGEST_TICKS = 200  # переваривание: сытый хищник не охотится
FLEE_DURATION_SEC = 1.0
FLEE_TICKS = int(FLEE_DURATION_SEC * FPS)
FLEE_TRIGGER_FRAC = 1 / 3    # хищник ближе vision*frac — травоядное бежит

# ── поиск соседей ────────────────────────────────────────────────────────────
SPATIAL_CELL_SIZE = 2000     # ≈ типичный vision

# ── статистика ───────────────────────────────────────────────────────────────
STATS_EVERY   = 30           # тиков между срезами истории
STATS_HISTORY = 4000         # сколько срезов держим в памяти
